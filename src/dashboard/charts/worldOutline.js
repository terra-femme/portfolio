/**
 * Low-poly world land outline, plus the equirectangular projection used to
 * draw it.
 *
 * Why this exists as hand-authored data: the dashboard has no runtime
 * dependencies and makes no network requests, so TopoJSON/GeoJSON from a CDN
 * was not an option. Real country geometry is also the wrong tool here -- this
 * map plots five datacenter regions as points, so the land only needs to say
 * "this is Earth" clearly enough for the viewer to locate a bubble. It is
 * rendered at low contrast for exactly that reason: it is context, not data.
 *
 * Coordinates are [longitude, latitude] in degrees. Shapes are deliberately
 * coarse (roughly 10-40 vertices each) and are NOT suitable for anything
 * cartographic -- no borders, no disputed territories, no area calculations.
 *
 * Antarctica is omitted and the latitude range is cropped to +83..-58, which
 * removes a band of empty ocean and polar ice that would otherwise take up a
 * third of the panel.
 */

export const LON_MIN = -180;
export const LON_MAX = 180;
export const LAT_MAX = 83;
export const LAT_MIN = -58;

/** Aspect ratio of the cropped map, used to size the SVG from its width. */
export const MAP_ASPECT = (LON_MAX - LON_MIN) / (LAT_MAX - LAT_MIN);

/**
 * Equirectangular (plate carree) projection: longitude maps linearly to x and
 * latitude linearly to y.
 *
 * Chosen over Mercator because Mercator inflates high latitudes enormously --
 * Sweden Central and UK South would drift far north of where a reader expects
 * them, and Greenland would rival Africa. Equirectangular stretches east-west
 * near the poles instead, which is far less misleading for point markers and
 * keeps the arithmetic trivial.
 */
export function project(lon, lat, width, height) {
  return {
    x: ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * width,
    y: ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * height,
  };
}

/** Turn a ring of [lon, lat] pairs into a closed SVG path. */
export function ringToPath(ring, width, height) {
  return ring
    .map(([lon, lat], i) => {
      const p = project(lon, lat, width, height);
      return `${i === 0 ? 'M' : 'L'} ${p.x.toFixed(1)} ${p.y.toFixed(1)}`;
    })
    .join(' ') + ' Z';
}

